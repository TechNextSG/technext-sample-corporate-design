def _scatter(key: str) -> tuple:
    """Stable pseudo-random start offset for an icon flying into the apps launcher."""
    import hashlib
    h = hashlib.md5(key.encode()).digest()
    return round((h[0] / 255 - .5) * 320), round((h[1] / 255 - .5) * 220), round((h[2] / 255 - .5) * 80)


